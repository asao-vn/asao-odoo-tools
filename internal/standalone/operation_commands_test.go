// 3. PLAN PARITY BETWEEN ALIAS AND GENERIC EXECUTE
// ---------------------------------------------------------------------------

func TestPlanParityBetweenAliasAndGenericExecute(t *testing.T) {
	server := httptest.NewServer(odoo19(func(w http.ResponseWriter, r *http.Request) {
		// Plan dry run should make ZERO calls to Odoo
		t.Errorf("plan dry run contacted provider: %s", r.URL.Path)
	}))
	defer server.Close()
	writeTestProfile(t, server.URL)

	testCases := []struct {
		name        string
		executeArgs []string
		aliasArgs   []string
	}{
		{
			name:        "people.employee.list",
			executeArgs: []string{"plan", "--profile", "lab-a", "--operation", "people.employee.list", "--limit", "5", "--output", "json"},
			aliasArgs:   []string{"people", "employee", "list", "--profile", "lab-a", "--limit", "5", "--plan", "--output", "json"},
		},
		{
			name:        "identity.contact.create",
			executeArgs: []string{"plan", "--profile", "lab-a", "--operation", "identity.contact.create", "--set", "name=Alice", "--output", "json"},
			aliasArgs:   []string{"identity", "contact", "create", "--profile", "lab-a", "--name", "Alice", "--plan", "--output", "json"},
		},
		{
			name:        "sales.quotation.update",
			executeArgs: []string{"plan", "--profile", "lab-a", "--operation", "sales.quotation.update", "--provider-target-id", "10", "--set", "client_order_ref=REF001", "--output", "json"},
			aliasArgs:   []string{"sales", "quotation", "update", "--profile", "lab-a", "--provider-target-id", "10", "--client_order_ref", "REF001", "--plan", "--output", "json"},
		},
	}

	for _, tc := range testCases {
		t.Run(tc.name, func(t *testing.T) {
			code1, out1, diag1 := runOdoo(t, tc.executeArgs...)
			if code1 != clicore.ExitOK {
				t.Fatalf("execute plan exited %d: %s\n%s", code1, out1.String(), diag1.String())
			}
			data1 := decode(t, out1)

			code2, out2, diag2 := runOdoo(t, tc.aliasArgs...)
			if code2 != clicore.ExitOK {
				t.Fatalf("alias plan exited %d: %s\n%s", code2, out2.String(), diag2.String())
			}
			data2 := decode(t, out2)

			// Compare the Plan outputs field-by-field
			for _, key := range []string{"operation", "provider", "providerResource", "expectedEffect", "readiness", "risk", "targetMediation", "evidenceClass"} {
				if data1[key] != data2[key] {
					t.Errorf("plan %s mismatch for key %q: execute=%v, alias=%v", tc.name, key, data1[key], data2[key])
				}
			}
			if !reflect.DeepEqual(data1["proposedInput"], data2["proposedInput"]) {
				t.Errorf("plan %s proposedInput mismatch: execute=%v, alias=%v", tc.name, data1["proposedInput"], data2["proposedInput"])
			}
			if !reflect.DeepEqual(data1["providerRoute"], data2["providerRoute"]) {
				t.Errorf("plan %s providerRoute mismatch: execute=%v, alias=%v", tc.name, data1["providerRoute"], data2["providerRoute"])
			}
		})
	}
}

