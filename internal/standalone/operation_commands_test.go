// 4. CALL IS ABSENT FROM SEMANTIC CATALOG
// ---------------------------------------------------------------------------

func TestCallIsAbsentFromSemanticCatalog(t *testing.T) {
	if _, ok := odoo.CatalogByID["call"]; ok {
		t.Fatal("call is in odoo.CatalogByID; must not be included in semantic catalog")
	}
	for _, op := range direct.Operations() {
		if op.ID == "call" || strings.HasPrefix(op.ID, "call.") {
			t.Fatalf("call found in direct.Operations(): %s", op.ID)
		}
	}
	for _, id := range direct.OperationIDs() {
		if id == "call" {
			t.Fatal("call found in direct.OperationIDs()")
		}
	}

	code, out, _ := runOdoo(t, "catalog", "list", "--output", "json")
	if code != clicore.ExitOK {
		t.Fatalf("catalog list failed: %s", out.String())
	}
	data := decode(t, out)
	items, ok := data["items"].([]interface{})
	if !ok {
		t.Fatal("catalog list missing items")
	}
	for _, item := range items {
		m := item.(map[string]interface{})
		if m["id"] == "call" {
			t.Fatal("call found in catalog list items")
		}
	}
}

