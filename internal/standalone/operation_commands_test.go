// 2. CONTRACT INPUT PARITY
// ---------------------------------------------------------------------------

func TestContractInputParity(t *testing.T) {
	root := standalone.RootFor("odoo")
	catalogOps := direct.Operations()

	for _, op := range catalogOps {
		cmd := standalone.FindOperationCommand(root, op.ID)
		if cmd == nil {
			t.Fatalf("missing command for %s", op.ID)
		}

		inputFlags := standalone.ContractInputFlags(op)
		if len(inputFlags) != len(op.Inputs) {
			t.Fatalf("operation %s: ContractInputFlags length %d != op.Inputs length %d", op.ID, len(inputFlags), len(op.Inputs))
		}

		// Ensure every contract input has an exact matching flag on the generated command
		for i, input := range op.Inputs {
			flag := inputFlags[i]
			if flag.Name != input.Name {
				t.Errorf("%s: flag.Name = %q, want %q", op.ID, flag.Name, input.Name)
			}
			if flag.Required != input.Required {
				t.Errorf("%s: flag %s Required = %v, want %v", op.ID, input.Name, flag.Required, input.Required)
			}
			if len(input.EnumValues) > 0 && !reflect.DeepEqual(flag.Enum, input.EnumValues) {
				t.Errorf("%s: flag %s Enum = %v, want %v", op.ID, input.Name, flag.Enum, input.EnumValues)
			}

			// Also verify the flag is present on the command's own flag set
			var foundOnCmd bool
			for _, cmdFlag := range cmd.Flags {
				if cmdFlag.Name == input.Name {
					foundOnCmd = true
					if cmdFlag.Kind != flag.Kind {
						t.Errorf("%s: flag %s Kind = %v, want %v", op.ID, input.Name, cmdFlag.Kind, flag.Kind)
					}
					if cmdFlag.Required != input.Required {
						t.Errorf("%s: cmdFlag %s Required = %v, want %v", op.ID, input.Name, cmdFlag.Required, input.Required)
					}
					break
				}
			}
			if !foundOnCmd {
				t.Errorf("%s: input flag --%s not found in cmd.Flags", op.ID, input.Name)
			}
		}
	}
}

