func runOdoo(t *testing.T, args ...string) (int, *bytes.Buffer, *bytes.Buffer) {
	t.Helper()
	out, diag := &bytes.Buffer{}, &bytes.Buffer{}
	code := clicore.Run(context.Background(), standalone.RootFor("odoo"), args, clicore.Streams{Out: out, Diagnostics: diag})
	return code, out, diag
}

