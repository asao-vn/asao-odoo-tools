func TestCLIRawCallSearchRead(t *testing.T) {
	calls := 0
	server := httptest.NewServer(odoo19(func(w http.ResponseWriter, r *http.Request) {
		calls++
		var req struct {
			Params struct {
				Service string        `json:"service"`
				Method  string        `json:"method"`
				Args    []interface{} `json:"args"`
			} `json:"params"`
		}
		if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
			t.Error(err)
			return
		}
		if req.Params.Service == "common" {
			json.NewEncoder(w).Encode(map[string]interface{}{"result": 1})
			return
		}
		a := req.Params.Args
		if req.Params.Method != "execute_kw" || a[3] != "res.partner" || a[4] != "search_read" {
			t.Errorf("wrong routing: method=%s, model=%v, odooMethod=%v", req.Params.Method, a[3], a[4])
		}
		json.NewEncoder(w).Encode(map[string]interface{}{
			"result": []interface{}{
				map[string]interface{}{"id": 10, "name": "Acme Inc"},
			},
		})
	}))
	defer server.Close()
	writeTestProfile(t, server.URL)

	code, out, diag := runOdoo(t, "call", "--profile", "lab-a",
		"--model", "res.partner",
		"--method", "search_read",
		"--args-json", `[[["name","=","Acme Inc"]]]`,
		"--kwargs-json", `{"fields":["name"],"limit":5}`,
		"--output", "json")

	if code != clicore.ExitOK {
		t.Fatalf("call failed with exit %d: %s\ndiag: %s", code, out.String(), diag.String())
	}

	data := decode(t, out)
	if data["raw"] != true {
		t.Errorf("raw = %v, want true", data["raw"])
	}
	if data["model"] != "res.partner" || data["method"] != "search_read" {
		t.Errorf("model/method = %v/%v", data["model"], data["method"])
	}
	if data["mutationAllowed"] != false {
		t.Errorf("mutationAllowed = %v, want false", data["mutationAllowed"])
	}
	results, ok := data["data"].([]interface{})
	if !ok || len(results) != 1 {
		t.Fatalf("expected 1 result in data, got %v", data["data"])
	}
	rec := results[0].(map[string]interface{})
	if rec["name"] != "Acme Inc" {
		t.Errorf("name = %v, want Acme Inc", rec["name"])
	}
}

func TestCLIRawCallMutationRefusedWithoutFlag(t *testing.T) {
	calls := 0
	server := httptest.NewServer(http.HandlerFunc(func(http.ResponseWriter, *http.Request) {
		calls++
	}))
	defer server.Close()
	writeTestProfile(t, server.URL)

	code, out, _ := runOdoo(t, "call", "--profile", "lab-a",
		"--model", "res.partner",
		"--method", "write",
		"--args-json", `[[1], {"name": "New"}]`,
		"--output", "json")

	if code == clicore.ExitOK {
		t.Fatal("mutating method without --allow-mutation must fail")
	}
	errObj := decodeError(t, out)
	if errObj["code"] != "RAW_MUTATION_NOT_ALLOWED" {
		t.Errorf("code = %v, want RAW_MUTATION_NOT_ALLOWED", errObj["code"])
	}
	if calls != 0 {
		t.Fatalf("refused mutation made %d HTTP requests, want 0", calls)
	}

	// Now with --allow-mutation
	server2 := httptest.NewServer(odoo19(func(w http.ResponseWriter, r *http.Request) {
		var req struct {
			Params struct {
				Service string `json:"service"`
			} `json:"params"`
		}
		json.NewDecoder(r.Body).Decode(&req)
		if req.Params.Service == "common" {
			json.NewEncoder(w).Encode(map[string]interface{}{"result": 1})
			return
		}
		json.NewEncoder(w).Encode(map[string]interface{}{"result": true})
	}))
	defer server2.Close()
	writeTestProfile(t, server2.URL)

	code, out, diag := runOdoo(t, "call", "--profile", "lab-a",
		"--model", "res.partner",
		"--method", "write",
		"--args-json", `[[1], {"name": "New"}]`,
		"--allow-mutation",
		"--output", "json")

	if code != clicore.ExitOK {
		t.Fatalf("mutating method with --allow-mutation failed: %s\ndiag: %s", out.String(), diag.String())
	}
	data := decode(t, out)
	if data["mutationAllowed"] != true {
		t.Errorf("mutationAllowed = %v, want true", data["mutationAllowed"])
	}
}

