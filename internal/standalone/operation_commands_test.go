func TestCLIDiscoverableGeneratedPathsInCommandsList(t *testing.T) {
	code, out, _ := runOdoo(t, "commands", "list", "--output", "json")
	if code != clicore.ExitOK {
		t.Fatalf("commands list exited %d: %s", code, out.String())
	}
	data := decode(t, out)
	raw, _ := json.Marshal(data["tree"])
	var tree clicore.CommandSpec
	if err := json.Unmarshal(raw, &tree); err != nil {
		t.Fatal(err)
	}

	foundCall := false
	foundEmployeeList := false
	foundEmployeeCreate := false
	foundQuotationUpdate := false

	walk(tree, func(spec clicore.CommandSpec) {
		switch spec.Command {
		case "odoo call":
			foundCall = true
		case "odoo people employee list":
			foundEmployeeList = true
		case "odoo people employee create":
			foundEmployeeCreate = true
		case "odoo sales quotation update":
			foundQuotationUpdate = true
		}
	})

	if !foundCall {
		t.Error("odoo call not found in odoo commands list")
	}
	if !foundEmployeeList {
		t.Error("odoo people employee list not found in odoo commands list")
	}
	if !foundEmployeeCreate {
		t.Error("odoo people employee create not found in odoo commands list")
	}
	if !foundQuotationUpdate {
		t.Error("odoo sales quotation update not found in odoo commands list")
	}
}
