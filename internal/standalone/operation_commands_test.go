func TestProjectionParityExactlyOnePathPerCatalogOperation(t *testing.T) {
	root := standalone.RootFor("odoo")
	catalogOps := direct.Operations()

	if len(catalogOps) != AcceptedCatalogSize {
		t.Fatalf("catalog count = %d, want %d", len(catalogOps), AcceptedCatalogSize)
	}

	seenPaths := map[string]string{}
	seenIDs := map[string]string{}

	for _, op := range catalogOps {
		cmd := standalone.FindOperationCommand(root, op.ID)
		if cmd == nil {
			t.Fatalf("operation %s has no generated command in odoo root", op.ID)
		}
		pathStr := cmd.PathString()
		if existingID, dup := seenPaths[pathStr]; dup {
			t.Fatalf("path %q generated by both %s and %s", pathStr, existingID, op.ID)
		}
		seenPaths[pathStr] = op.ID

		if existingPath, dup := seenIDs[op.ID]; dup {
			t.Fatalf("operation %s generated multiple paths: %s and %s", op.ID, existingPath, pathStr)
		}
		seenIDs[op.ID] = pathStr

		if cmd.Operation != op.ID {
			t.Errorf("cmd.Operation = %q, want %q", cmd.Operation, op.ID)
		}
		if cmd.TargetRule != op.TargetRequirement {
			t.Errorf("cmd %s: cmd.TargetRule = %q, want %q", op.ID, cmd.TargetRule, op.TargetRequirement)
		}
		if cmd.Readiness != op.Readiness {
			t.Errorf("cmd %s: cmd.Readiness = %q, want %q", op.ID, cmd.Readiness, op.Readiness)
		}
		if cmd.Risk != op.Risk {
			t.Errorf("cmd %s: cmd.Risk = %q, want %q", op.ID, cmd.Risk, op.Risk)
		}
	}

	if len(seenPaths) != len(catalogOps) {
		t.Fatalf("generated paths count %d != catalog count %d", len(seenPaths), len(catalogOps))
	}
}

func TestNoGeneratedPathNamesUnknownOperationID(t *testing.T) {
	root := standalone.RootFor("odoo")
	var allGeneratedOps []string

	var collectOps func(*clicore.Command)
	collectOps = func(c *clicore.Command) {
		if c.Operation != "" {
			allGeneratedOps = append(allGeneratedOps, c.Operation)
		}
		for _, child := range c.Children {
			collectOps(child)
		}
	}
	collectOps(root)

	if len(allGeneratedOps) != AcceptedCatalogSize+AcceptedSurfaceSize {
		t.Fatalf("collected %d generated operations, want %d", len(allGeneratedOps), AcceptedCatalogSize+AcceptedSurfaceSize)
	}

	for _, id := range allGeneratedOps {
		if _, ok := odoo.LookupStandaloneOperation(id); !ok {
			t.Fatalf("generated command names unknown catalog operation id %q", id)
		}
	}
}

